using System;
using System.Collections.Generic;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Input;
using System.Windows.Media;
using System.Windows.Media.Imaging;
using System.Windows.Shapes;
using FAAM.UI.ViewModels.Sections;
using Horizon.Engine;

namespace FAAM.UI.Views.Sections;

/// <summary>
/// The Device Registration section's view — owns the feed geometry: turns a click into
/// camera source pixels (MoveClick jog, or a registration point), and draws the picked
/// points, their average and the outline preview over the live image so they stay glued to
/// the physical spot even when the camera is re-jogged. The registered tool's live glyph is
/// the shared <see cref="ToolOverlayView"/>.
/// </summary>
public partial class DeviceRegistrationSectionView : UserControl
{
    private static readonly Brush PointBrush = new SolidColorBrush(Color.FromRgb(0x00, 0xE6, 0x76));
    private static readonly Brush AvgBrush = new SolidColorBrush(Color.FromRgb(0xFF, 0xA0, 0x00));
    private static readonly Brush OutlineBrush = new SolidColorBrush(Color.FromRgb(0xC8, 0xC8, 0xC8));

    private DeviceRegistrationSectionViewModel? _vm;
    private readonly List<UIElement> _pointMarks = new();
    private readonly Rectangle _preview = new()
    {
        Stroke = OutlineBrush, StrokeThickness = 1.5, StrokeDashArray = new DoubleCollection { 4, 3 },
        Fill = Brushes.Transparent, Visibility = Visibility.Collapsed,
    };
    private readonly Line _avgH = new() { Stroke = AvgBrush, StrokeThickness = 2, Visibility = Visibility.Collapsed };
    private readonly Line _avgV = new() { Stroke = AvgBrush, StrokeThickness = 2, Visibility = Visibility.Collapsed };

    public DeviceRegistrationSectionView()
    {
        InitializeComponent();
        PointOverlay.Children.Add(_preview);
        PointOverlay.Children.Add(_avgH);
        PointOverlay.Children.Add(_avgV);
        DataContextChanged += OnDataContextChanged;
        MainImage.SizeChanged += (_, _) => RedrawPoints();
        Unloaded += (_, _) => Bind(null);
        Loaded += (_, _) => Bind(DataContext as DeviceRegistrationSectionViewModel);
    }

    private void OnDataContextChanged(object sender, DependencyPropertyChangedEventArgs e)
        => Bind(e.NewValue as DeviceRegistrationSectionViewModel);

    /// <summary>
    /// (Re)binds to the section model. The view is regenerated by the section DataTemplate
    /// each time the operator returns here, so everything hooked on bind is unhooked on unbind.
    /// </summary>
    private void Bind(DeviceRegistrationSectionViewModel? vm)
    {
        if (ReferenceEquals(_vm, vm)) return;
        if (_vm != null)
        {
            _vm.Ticked -= RedrawPoints;
            _vm.Camera.PropertyChanged -= OnCameraPropertyChanged;
            ToolOverlay.SetActive(false);
            ToolOverlay.Detach();
        }
        _vm = vm;
        if (_vm == null) return;

        _vm.Ticked += RedrawPoints;
        _vm.Camera.PropertyChanged += OnCameraPropertyChanged;
        ToolOverlay.Attach(_vm.Host, MainImage, cover: false);
        ToolOverlay.Camera = _vm.Camera.SelectedCamera;
        ToolOverlay.SetActive(true);
        RedrawPoints();
    }

    private void OnCameraPropertyChanged(object? sender, System.ComponentModel.PropertyChangedEventArgs e)
    {
        if (_vm != null && e.PropertyName == nameof(CameraSectionViewModel.SelectedCamera))
            ToolOverlay.Camera = _vm.Camera.SelectedCamera;
    }

    // The feed click modes are exclusive: arming one disarms the others.
    private void OnMoveArmed(object sender, RoutedEventArgs e) { PickToggle.IsChecked = false; OutlineToggle.IsChecked = false; }
    private void OnPickArmed(object sender, RoutedEventArgs e) { MoveToggle.IsChecked = false; OutlineToggle.IsChecked = false; }
    private void OnOutlineArmed(object sender, RoutedEventArgs e) { MoveToggle.IsChecked = false; PickToggle.IsChecked = false; }

    private async void OnFeedClick(object sender, MouseButtonEventArgs e)
    {
        if (_vm == null || MainImage.Source is not BitmapSource bmp) return;
        var p = e.GetPosition(MainImage);
        double availW = MainImage.ActualWidth, availH = MainImage.ActualHeight;
        if (p.X < 0 || p.Y < 0 || p.X > availW || p.Y > availH) return;   // letterbox margin

        if (PickToggle.IsChecked == true || OutlineToggle.IsChecked == true)
        {
            double scale = MoveClick.DisplayScale(availW, availH, bmp.PixelWidth, bmp.PixelHeight, cover: false);
            if (scale <= 0) return;
            var (dx, dy) = ToolOverlayMath.FromDisplay(p, availW, availH, scale);
            double sx = bmp.PixelWidth / 2.0 + dx, sy = bmp.PixelHeight / 2.0 + dy;
            if (PickToggle.IsChecked == true)
                await _vm.AddPointAsync(sx, sy, bmp.PixelWidth, bmp.PixelHeight);
            else
                await _vm.AddOutlineCornerAsync(sx, sy, bmp.PixelWidth, bmp.PixelHeight);
            RedrawPoints();
            return;
        }

        if (MoveToggle.IsChecked == true)
        {
            var host = _vm.Host;
            if (!host.Session.Has(AccessPolicy.Jog)) return;
            var m = MoveClick.Measure(host, p, availW, availH, bmp.PixelWidth, bmp.PixelHeight);
            if (m is not { } meas) return;
            await MoveClick.JogAsync(host, meas, msg =>
                host.Log.Add(new LogEntry(LogLevel.Info, DateTimeOffset.Now, "Registration", msg)));
        }
    }

    /// <summary>
    /// Draws every picked point, the average marker and the outline preview at their
    /// current on-screen place — camera-frame mm relative to the camera device's live pose,
    /// through the same mm/pixel + sign mapping the tool overlay uses.
    /// </summary>
    private void RedrawPoints()
    {
        foreach (var m in _pointMarks) PointOverlay.Children.Remove(m);
        _pointMarks.Clear();
        _preview.Visibility = _avgH.Visibility = _avgV.Visibility = Visibility.Collapsed;

        if (_vm == null || _vm.CameraDevice == null || MainImage.Source is not BitmapSource bmp) return;
        double availW = MainImage.ActualWidth, availH = MainImage.ActualHeight;
        if (availW <= 0 || availH <= 0) return;
        double scale = MoveClick.DisplayScale(availW, availH, bmp.PixelWidth, bmp.PixelHeight, cover: false);
        if (scale <= 0) return;

        var cam = _vm.Host.Engine.Motion.GetState(_vm.CameraDevice);
        if (!cam.Valid) return;
        var settings = _vm.Host.Settings.Current;
        PointOverlay.Width = availW;
        PointOverlay.Height = availH;

        Point? Place(double frameX, double frameY)
        {
            var px = ToolOverlayMath.MmToSourcePx(frameX - cam.Position.X, frameY - cam.Position.Y, settings);
            return px is { } o ? ToolOverlayMath.ToDisplay(o.DxPx, o.DyPx, availW, availH, scale) : null;
        }

        foreach (var row in _vm.Points)
        {
            if (Place(row.Point.CameraFrameX, row.Point.CameraFrameY) is not { } d) continue;
            var dot = new Ellipse { Width = 9, Height = 9, Stroke = PointBrush, StrokeThickness = 2, Fill = Brushes.Transparent };
            Canvas.SetLeft(dot, d.X - 4.5); Canvas.SetTop(dot, d.Y - 4.5);
            var tag = new TextBlock { Text = row.Index.ToString(), Foreground = PointBrush, FontSize = 11, FontWeight = FontWeights.Bold };
            Canvas.SetLeft(tag, d.X + 6); Canvas.SetTop(tag, d.Y - 14);
            PointOverlay.Children.Add(dot); PointOverlay.Children.Add(tag);
            _pointMarks.Add(dot); _pointMarks.Add(tag);
        }

        // Picked outline corners (grey squares).
        foreach (var corner in _vm.OutlineCorners)
        {
            if (Place(corner.X, corner.Y) is not { } d) continue;
            var sq = new Rectangle { Width = 8, Height = 8, Stroke = OutlineBrush, StrokeThickness = 2, Fill = Brushes.Transparent };
            Canvas.SetLeft(sq, d.X - 4); Canvas.SetTop(sq, d.Y - 4);
            PointOverlay.Children.Add(sq);
            _pointMarks.Add(sq);
        }

        if (_vm.Average is { } avg && Place(avg.X, avg.Y) is { } c)
        {
            _avgH.X1 = c.X - 12; _avgH.X2 = c.X + 12; _avgH.Y1 = _avgH.Y2 = c.Y;
            _avgV.Y1 = c.Y - 12; _avgV.Y2 = c.Y + 12; _avgV.X1 = _avgV.X2 = c.X;
            _avgH.Visibility = _avgV.Visibility = Visibility.Visible;

            // Outline preview: anchored to the average, shifted by the box offset.
            if (settings.MmPerPixel > 0 && _vm.OutlineBox is { } box
                && Place(avg.X + box.OffX, avg.Y + box.OffY) is { } bc)
            {
                double wPx = box.W / settings.MmPerPixel * scale, hPx = box.L / settings.MmPerPixel * scale;
                _preview.Width = wPx; _preview.Height = hPx;
                Canvas.SetLeft(_preview, bc.X - wPx / 2); Canvas.SetTop(_preview, bc.Y - hPx / 2);
                _preview.Visibility = Visibility.Visible;
            }
        }
    }
}
